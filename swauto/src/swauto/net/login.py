"""Login flow — HubUserLogin request builder, response parser, session wiring.

Clean-room port of the documented login (docs/02 §5, docs/04 §1) grounded in
the A1 oracle probe (work/autosw/trace/_A1_login_outcome.md):

- the login request is an **8-field** body (not the 4-field command stub):
  ``{channel_uid, command, infocsv, loginextend_refcount, proto_ver,
  session_key, ts_val, wizard_id}``. The extra 4 fields are added by the
  transport layer from the session config + a fresh ``ts_val``.
- ``fetch_version`` runs first against ``/api/version_info_c2.php`` to obtain
  ``infocsv``/``proto_ver``.
- the response's ``session_key``/``session_key_node`` are the paired auth
  tokens; the port's default wiring is ``session_key ← response.session_key``
  and ``channel_uid ← response.session_key_node`` (the self-consistent pair —
  §4 of the A1 outcome). The exact source assignment statement is the one
  **live-gated** leg (not observed offline); it is marked below.
- ``ts_val`` is a per-send scaled timestamp generated by the app — the exact
  basis is not offline-recoverable, so it is caller-suppliable with a
  documented approximate default.
- the version_info_c2 *request* is a **distinct 4-field** body (not the login
  envelope): ``{game_index, proto_ver, channel_uid, sec_ver}``, recovered
  verbatim from the oracle (B6). The real response's ``version_data`` is a
  **list of per-topic rows** (``ban_appid``/``cdnres``/``infocsv``/``intro``/
  ``protocol``/``text``) — recovered live 2026-09-07.

This module is transport-agnostic: it calls a ``Transport``-shaped seam
(exactly like :mod:`.session`) so offline tests replay the captured 7280513
response through a :class:`~.transport.ScriptedTransport`. The live drivers
(:class:`LiveVersionFetcher`, the ``swauto live-login`` CLI) additionally
reproduce the captured gateway headers via
:class:`~.transport.GatewayTransport`.

**Live-auth boundary (B6):** an 8-field ``HubUserLogin`` over the captured
headers does **not** authenticate alone — the real gateway refused it with
``ret_code 1006`` (not authenticated) in a live run. Docs/07 §1.3 and the case
report §3.3 say the app first performs an RSA-4096 session-key exchange whose
wire step no offline capture reconstructs (A1 §5); that leg is the live-gated
remainder. See work/autosw/trace/_B6_live_login_outcome.md.
"""

