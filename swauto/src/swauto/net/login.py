# Recovered login constants (captured wire body + fetch_version defaults —
# A1 probe: infocsv "4.08.41_Zdu2ehyV", proto_ver 12160 on the working profile).
DEFAULT_PROTO_VER = 12160
DEFAULT_INFOCSV = "4.08.41_Zdu2ehyV"
DEFAULT_GAME_INDEX = 2623

# Endpoints (A1 probe, captured real POSTs).
ENDPOINT_LOGIN = "/api/gateway_c2.php"
ENDPOINT_VERSION = "/api/version_info_c2.php"

# Response session contract fields carried by every HubUserLogin capture.
SESSION_CONTRACT_FIELDS = (
    "wizard_id", "this_server_id", "session_key", "session_key_node",
    "reqid", "ts_val", "tvalue", "tvaluelocal", "tzoffset", "tzone",
    "country", "account_info",
)


def version_topics(payload: dict, target: Any | None = None) -> dict:
    """Normalise a version_info_c2 response into per-topic config rows.

    The real response (recovered live 2026-09-07) carries ``version_data`` as a
    LIST of rows keyed by ``topic`` (``ban_appid``/``cdnres``/``infocsv``/
    ``intro``/``protocol``/``text``), each with ``game_index``/``name``/
    ``version``/``cdnroot``. Returns ``{topic: row}``. When ``target`` is given,
    adopt the ``infocsv`` and ``protocol`` rows' ``version`` onto its
    ``infocsv``/``proto_ver`` attrs (the oracle's flow refreshes those from this
    response). Tolerates dict-form ``version_data`` too.
    """
    vd = payload.get("version_data", [])
    topics = {}
    if isinstance(vd, dict):
        vd = [vd]
    for row in vd:
        if isinstance(row, dict) and row.get("topic"):
            topics[str(row["topic"])] = row
    if target is not None:
        inf = topics.get("infocsv")
        prot = topics.get("protocol")
        if inf and inf.get("version"):
            target.infocsv = str(inf["version"])
        if prot and prot.get("version") and str(prot["version"]).isdigit():
            target.proto_ver = int(prot["version"])
    return topics


def build_version_request(
    game_index: int = DEFAULT_GAME_INDEX,
    *,
    proto_ver: int = DEFAULT_PROTO_VER,
    channel_uid: str = "",
    sec_ver: str = VERSION_SEC_VER,
) -> dict:
    """Assemble the exact 4-field version_info_c2 request body.

    Captured verbatim from the oracle's real ``fetch_version`` call
    (work/autosw/trace/_version_request_capture.py): this is a *distinct*
    request family from the 8-field HubUserLogin envelope — it carries no
    ``command``, no ``session_key``/``infocsv``/``ts_val``; just
    ``game_index``/``proto_ver``/``channel_uid``/``sec_ver``. ``channel_uid``
    is 0 on a fresh pre-login fetch (the captured default); a logged-in
    relogin fetch would carry the account's UID.
    """
    return {
        "game_index": game_index,
        "proto_ver": proto_ver,
        "channel_uid": channel_uid,
        "sec_ver": sec_ver,
    }


def scaled_ts_val(offset: float = 203_000_000.0) -> int:
    """Approximate per-send timestamp field.

    The real ``ts_val`` is a per-send scaled clock (A1: ~1.99e9, roughly
    ``unix + ~203e6``) whose exact basis the offline probe did not pin. This
    returns ``unix_time + offset`` so request bodies are plausible; the caller
    may pass an exact value instead (offline replay tests do).
    """
    return int(time.time() + offset)


class VersionFetcher(Protocol):
    def __call__(self, game_index: int) -> dict: ...


@dataclass
class SessionState:
    """Session contract parsed from a HubUserLogin response.

    ``skey``/``cuid`` are the instance attrs the request layer signs with
    (self.skey → wire ``session_key``, self.cuid → wire ``channel_uid``, A1
    body-diff). The default wiring below (skey=session_key, cuid=session_key_node)
    is the self-consistent pair the profile proves; the exact source assignment
    is the live-gated leg and is documented in :func:`parse_login_response`.
    """
    wizard_id: int | None = None
    server_id: int | None = None
    server_host: str = ""
    session_key: str = ""
    session_key_node: str = ""
    reqid: str = ""
    account_info: dict = field(default_factory=dict)

    # request-signing attrs (wire role mapping — A1 §3)
    skey: str = ""
    cuid: str = ""

    @property
    def protocol(self) -> int:
        return DEFAULT_PROTO_VER

    @property
    def infocsv(self) -> str:
        return DEFAULT_INFOCSV


def build_login_request(
    wizard_id: int,
    *,
    proto_ver: int = DEFAULT_PROTO_VER,
    infocsv: str = DEFAULT_INFOCSV,
    session_key: str = "",
    channel_uid: str = "",
    ts_val: int | None = None,
) -> dict:
    """Assemble the exact 8-field HubUserLogin body (A1 §1).

    ``session_key``/``channel_uid`` are the *wire* request field names; the
    caller passes the pre-login values (typically empty, or the stored token
    on a relogin).
    """
    return {
        "channel_uid": channel_uid,
        "command": "HubUserLogin",
        "infocsv": infocsv,
        "loginextend_refcount": 0,
        "proto_ver": proto_ver,
        "session_key": session_key,
        "ts_val": ts_val if ts_val is not None else scaled_ts_val(),
        "wizard_id": wizard_id,
    }


def parse_login_response(resp: dict) -> SessionState:
    """Parse a HubUserLogin response into the session contract.

    Fields read (all captures carry these): ``wizard_id``, ``this_server_id``,
    ``session_key``, ``session_key_node``, ``reqid``, ``account_info``, and
    (not mapped to state) ``ts_val``/``tvalue``/``tzoffset``/``tzone``/
    ``country``.

    The request-signing pair is defaulted to the self-consistent mapping
    ``skey=session_key``, ``cuid=session_key_node`` (A1 §4). Reconciliation
    probe (field-role): this is the ONLY wiring consistent with the oracle —
    a spy-wrapped ``account_info`` showed the real ``send()`` never reads
    ``account_info`` at all, and the wire auth pair is drawn purely from
    ``self.cuid``/``self.skey`` (seeded = ``session_key``/``session_key_node``).
    The account's platform UID (``account_info.channel_uid``, e.g. the integer
    131301622) is a distinct record and plays **no role** in signing. The only
    residual live-gated leg is the *response-field→attr assignment statement*
    (it lives in an orchestrating caller not offline-reachable); the emitted
    value is proven to be the paired token.
    """
    state = SessionState(
        wizard_id=resp.get("wizard_id"),
        server_id=resp.get("this_server_id"),
        session_key=resp.get("session_key", "") or "",
        session_key_node=resp.get("session_key_node", "") or "",
        reqid=resp.get("reqid", "") or "",
        account_info=dict(resp.get("account_info", {}) or {}),
    )
    state.skey = state.session_key
    state.cuid = state.session_key_node
    return state


def apply_session(state: SessionState, target: Any) -> None:
    """Wire the parsed session contract onto a Session/BattleClient.

    Populates exactly the attrs the request layer reads (A1 field-role map):
    ``wizard_id``, ``server_id``, ``skey`` (→ wire session_key), ``cuid`` (→
    wire channel_uid), and stores the response tokens for reference.
    """
    target.wizard_id = state.wizard_id
    target.server_id = state.server_id
    target.skey = state.skey
    target.cuid = state.cuid
    target.session_key = state.session_key
    target.session_key_node = state.session_key_node
    target.reqid = state.reqid
    target.account_info = state.account_info


class LoginClient:
    """Transport-backed login: version fetch + HubUserLogin + session state.

    The gateway transport is a ``Transport``-shaped callable (command, payload)
    -> dict (same seam as :class:`~.session.Session`), so offline tests drive a
    :class:`~.transport.ScriptedTransport` that answers ``HubUserLogin`` with
    the captured 7280513 response.
    """

    def __init__(self, transport: Transport,
                 server_host: str = "", *, proto_ver: int = DEFAULT_PROTO_VER,
                 infocsv: str = DEFAULT_INFOCSV,
                 fetch_version: VersionFetcher | None = None) -> None:
        self._transport = transport
        self.server_host = server_host
        self.proto_ver = proto_ver
        self.infocsv = infocsv
        self._fetch_version = fetch_version

    def fetch_version(self, game_index: int = DEFAULT_GAME_INDEX) -> dict:
        """Version/config fetch (``/api/version_info_c2.php``).

        A caller-supplied ``fetch_version`` (e.g.
        :class:`LiveVersionFetcher`) performs the real POST; the version
        response's ``proto_ver``/``infocsv`` are adopted (the oracle sets
        ``self.protocol``/``self.infocsv`` from the same response). Without a
        fetcher the caller-configured constants stand.

        The real response's ``version_data`` is a **list of per-topic rows**
        (``topic: ban_appid / cdnres / infocsv / intro / protocol / text``,
        recovered live 2026-09-07); ``infocsv`` and ``protocol`` rows carry the
        two config values the login uses.
        """
        if self._fetch_version is not None:
            vinfo = self._fetch_version(game_index)
            version_topics(vinfo, self)   # adopt proto_ver/infocsv (in place)
            return vinfo
        log.info("No version fetcher wired; using configured proto_ver=%s infocsv=%s",
                 self.proto_ver, self.infocsv)
        return {"proto_ver": self.proto_ver, "infocsv": self.infocsv}

    def login_response(self, wizard_id: int, *, session_key: str = "",
                       channel_uid: str = "", ts_val: int | None = None,
                       blocked: bool = False) -> tuple[dict | None, SessionState | None]:
        """Send HubUserLogin and return ``(raw_response, state)``.

        ``session_key``/``channel_uid`` are the pre-login wire request values
        (empty on a fresh login; the stored tokens on a relogin). The **raw
        response is the full account snapshot** (docs/07 §1.4), so it is
        surfaced alongside the parsed state for callers that persist a fresh
        profile. When the gateway refuses the login (non-zero ``ret_code`` /
        block flag) both are ``None`` — the account is not authenticated.
        """
        body = build_login_request(
            wizard_id, proto_ver=self.proto_ver, infocsv=self.infocsv,
            session_key=session_key, channel_uid=channel_uid, ts_val=ts_val)
        log.info("HubUserLogin (wizard %s)", wizard_id)
        resp = self._transport("HubUserLogin", body)
        if self.check_login_block(resp):
            if blocked:
                log.warning("HubUserLogin refused: %s", resp.get("ret_code"))
            return None, None
        return resp, parse_login_response(resp)

    def login(self, wizard_id: int, *, session_key: str = "",
              channel_uid: str = "", ts_val: int | None = None) -> SessionState | None:
        """Send HubUserLogin and return the parsed session state (see
        :meth:`login_response` for the raw snapshot body too)."""
        _, state = self.login_response(wizard_id, session_key=session_key,
                                       channel_uid=channel_uid, ts_val=ts_val)
        return state

    def manual_relogin(self, wizard_id: int, *, session_key: str = "",
                       channel_uid: str = "", ts_val: int | None = None,
                       game_index: int = DEFAULT_GAME_INDEX) -> SessionState:
        """Refreshes expired session tokens (docs/04 §Category-1 manual_relogin).

        Mirrors the A1 probe of the real ``manual_relogin``: it runs the
        version fetch first (to refresh ``infocsv``/``proto_ver``), then re-
        issues the identical 8-field ``HubUserLogin`` with a fresh ``ts_val``.
        ``session_key``/``channel_uid`` carry the still-valid stored tokens so
        the re-auth request is signed; the fresh response's session contract is
        returned for re-wiring onto the session.

        Live-gated note: the original's deeper relogin also reloads a
        ``monsters.data``-backed config and writes ``server_host``/``id`` from
        the version response, whose wire shape is not offline-reconstructible
        (A1 §5). This shell keeps the request/response boundary faithful so a
        wired ``version fetcher`` + transport can cover that leg later.
        """
        log.info("manual_relogin (wizard %s)", wizard_id)
        self.fetch_version(game_index)  # best-effort; constants stand if unwired
        return self.login(wizard_id, session_key=session_key,
                          channel_uid=channel_uid, ts_val=ts_val)

    def check_login_block(self, resp: dict) -> bool:
        """Verifies whether the account is flagged/banned (docs/04 §Category-1
        checkLoginBlock). A login response is treated as blocked when the
        gateway returns a non-zero ``ret_code`` or an explicit block flag; a
        normal ``ret_code == 0`` login is not blocked."""
        if resp.get("ret_code", 0) != 0:
            return True
        return bool(resp.get("login_block") or resp.get("is_banned") or False)


class LiveVersionFetcher:
    """Live ``version_info_c2`` fetcher over a :class:`GatewayTransport`.

    The version endpoint returns the *same* zlib-envelope body as every other
    gateway response (base64(AES-CBC(zlib(json)))), so the fetcher encrypts the
    4-field request and decrypts the response through the shared
    :mod:`swauto.net.crypto` chain. The returned dict carries the parsed
    response with a ``version_topics`` entry ({topic: row} — the real
    ``version_data`` is a list of per-topic rows) and a top-level ``ret_code``.

    This is the live-only leg of the login flow: it issues a real POST against
    the operator's gateway and is never invoked implicitly. Live-proven
    (B6, 2026-09-07): the version fetch succeeds end-to-end.
    """

    def __init__(self, transport, version_url: str = "", *,
                 key_version: int = 2, custom_key: str = "",
                 channel_uid: str = "", game_index: int = DEFAULT_GAME_INDEX,
                 proto_ver: int = DEFAULT_PROTO_VER) -> None:
        self._transport = transport
        self.version_url = version_url
        self.key_version = key_version
        self.custom_key = custom_key
        self.channel_uid = channel_uid
        self.game_index = game_index
        self.proto_ver = proto_ver

    def __call__(self, game_index: int | None = None) -> dict:
        idx = game_index if game_index is not None else self.game_index
        body = build_version_request(idx, proto_ver=self.proto_ver,
                                     channel_uid=self.channel_uid)
        wire = crypto.encrypt_request(
            json.dumps(body), self.key_version, self.custom_key)
        log.info("POST version_info_c2 (game_index %s)", idx)
        raw = self._transport.post(self.version_url, wire.encode())
        plain = crypto.decrypt_response(raw, self.key_version, self.custom_key)
        parsed = json.loads(plain)
        # Attach the normalised per-topic rows + ret_code so callers/LoginClient
        # read a stable contract regardless of dict-vs-list version_data.
        parsed["version_topics"] = version_topics(parsed)
        parsed.setdefault("ret_code", 0)
        return parsed
